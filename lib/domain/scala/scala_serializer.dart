import 'keyboard_mapping.dart';
import 'scala_note_helper.dart';
import 'scala_scale.dart';

/// Serializer for generating Huygens-Fokker standard Scala (.scl) and (.kbm) file formats.
class ScalaSerializer {
  const ScalaSerializer();

  /// Serializes a [ScalaScale] into a standard `.scl` formatted string.
  String serializeScl(
    ScalaScale scale, {
    bool includeNoteAnnotations = true,
    int centsDecimals = 3,
  }) {
    final buffer = StringBuffer();

    // 1. Header comments with optional metadata
    final filenameSafeName = scale.name
        .trim()
        .replaceAll(RegExp(r'\s+'), '_')
        .replaceAll(RegExp(r'[^\w\-]'), '');
    buffer.writeln(
      '! ${filenameSafeName.isNotEmpty ? filenameSafeName : "scale"}.scl',
    );

    if (scale.version.isNotEmpty) {
      buffer.writeln('! version=${scale.version}');
    }
    if (scale.abbreviation.isNotEmpty) {
      buffer.writeln('! abbreviation=${scale.abbreviation}');
    }
    if (scale.description.isNotEmpty) {
      buffer.writeln(
        '! description=${scale.description.replaceAll("\n", " ")}',
      );
    }
    buffer.writeln('!');

    // 2. Scale name/description (first non-comment line)
    buffer.writeln(scale.name.replaceAll('\n', ' '));

    // 3. Number of notes (second non-comment line)
    buffer.writeln('${scale.count}');
    buffer.writeln('!');

    // 4. Pitch lines
    for (final interval in scale.intervals) {
      if (interval.rational != null) {
        final r = interval.rational!;
        buffer.write(' ${r.numerator}/${r.denominator}');
      } else {
        // Cents format: ensure a decimal point exists even if integer cents
        var centsStr = interval.cents.toStringAsFixed(centsDecimals);
        if (!centsStr.contains('.')) {
          centsStr = '$centsStr.0';
        }
        buffer.write(' $centsStr');
      }

      if (includeNoteAnnotations && interval.note != null) {
        final noteStr = ScalaNoteHelper.formatNoteForScala(interval.note!);
        buffer.write('    note=$noteStr');
      }

      buffer.writeln();
    }

    return buffer.toString();
  }

  /// Serializes a [KeyboardMapping] into a standard `.kbm` formatted string.
  String serializeKbm(KeyboardMapping mapping) {
    final buffer = StringBuffer();
    buffer.writeln('! Keyboard Mapping (.kbm) generated by Tuner Flutter');
    buffer.writeln('!');
    buffer.writeln('! Size of map (number of keys to map):');
    buffer.writeln('${mapping.mapSize}');
    buffer.writeln('! First MIDI note number to retune:');
    buffer.writeln('${mapping.firstMidiNote}');
    buffer.writeln('! Last MIDI note number to retune:');
    buffer.writeln('${mapping.lastMidiNote}');
    buffer.writeln('! Middle note where degree 0 is placed (usually 60 = C4):');
    buffer.writeln('${mapping.middleMidiNote}');
    buffer.writeln('! Reference note for given frequency (usually 69 = A4):');
    buffer.writeln('${mapping.referenceMidiNote}');
    buffer.writeln('! Reference frequency in Hz:');
    buffer.writeln('${mapping.referenceFrequency}');
    buffer.writeln('! Scale degree for formal octave:');
    buffer.writeln('${mapping.scaleDegreeForOctave}');
    buffer.writeln('! Key mapping pattern (degree index or "x" for unmapped):');

    for (final deg in mapping.keyPattern) {
      if (deg < 0) {
        buffer.writeln('x');
      } else {
        buffer.writeln('$deg');
      }
    }

    return buffer.toString();
  }
}
